/**
 * Read-only corpus audit for evaluators.
 *
 *   pnpm tsx scripts/rag-audit.ts
 *
 * Reads the real retrieval database (no writes), joins it against the curated
 * manifest and the review ledger, and regenerates the evidence package under
 * `docs/rag-evidence/`:
 *
 *   RAG_SOURCE_INVENTORY.csv   every document with publisher, licence, source
 *   RAG_SOURCE_INVENTORY.json  the same rows, machine-readable
 *   RAG_CORPUS_REPORT.md       totals, publishers, licences and the pipeline
 *
 * The script exits non-zero when the audit finds a discrepancy (a manifest entry
 * that is not indexed, an indexed document that is not in the manifest, a URL,
 * publisher or licence that differs between the two, an empty passage, or a
 * passage count that does not add up), so a passing run is evidence rather than
 * decoration.
 */
import fs from "node:fs";
import path from "node:path";

import Database from "better-sqlite3";

import { reviewFor } from "@/lib/corpus/reviews";
import { CORPUS_SOURCES } from "@/lib/corpus/sources";
import {
  buildInventory,
  inventoryToCsv,
  type Inventory,
} from "@/lib/corpus/inventory";
import { DB_PATH } from "@/lib/config";

const OUT_DIR = path.join(process.cwd(), "docs", "rag-evidence");

function line(values: (string | number | null)[]): string {
  return values
    .map((value) => {
      if (value === null) return "—";
      const text = String(value);
      return /[|]/.test(text) ? text.replace(/\|/g, "\\|") : text;
    })
    .join(" | ");
}

function buildReport(inventory: Inventory, extra: {
  embeddedPassages: number;
  totalEmbeddings: number;
  ingestionRuns: number;
  revisionCount: number;
}): string {
  const publishedOn = new Date(inventory.generatedAt).toISOString().slice(0, 10);
  const notReviewed = inventory.rows.filter(
    (row) => row.reviewStatus === "not-reviewed",
  ).length;
  const searchable = inventory.rows.filter((row) => row.searchable).length;

  return `# RAG corpus report

Generated by \`pnpm tsx scripts/rag-audit.ts\` on ${inventory.generatedAt} (file date ${publishedOn}).
Every number below is read from the live retrieval database and the curated
manifest at run time; none of it is transcribed by hand.

## Verified totals

| Measure | Value | Where it comes from |
| --- | --- | --- |
| Source documents | ${inventory.documentCount} | \`documents\` table in ${inventory.database} |
| Indexed passages | ${inventory.passageCount} | \`chunks\` table |
| Passages with an embedding | ${extra.embeddedPassages} of ${extra.totalEmbeddings} | \`chunks.embedding IS NOT NULL\` |
| Searchable documents (at least one passage) | ${searchable} of ${inventory.documentCount} | derived |
| Publishers | ${inventory.publishers.length} | distinct \`documents.publisher\` |
| Distinct licences | ${inventory.licences.length} | distinct \`documents.licence\` |
| Manifest entries | ${CORPUS_SOURCES.length} | \`lib/corpus/sources.ts\` |
| Ingestion run records | ${extra.ingestionRuns} | \`ingestion_runs\` table |
| Document revisions recorded | ${extra.revisionCount} | \`document_revisions\` table |
| Retrieval backend | ${inventory.backend} | \`lib/db/sqlite-store.ts\` |
| Documents with a recorded review | ${inventory.documentCount - notReviewed} | \`lib/corpus/source-reviews.json\` (currently empty, so 0) |

## Publishers

| Publisher | Documents |
| --- | --- |
${inventory.publishers.map((row) => `| ${row.publisher} | ${row.documents} |`).join("\n")}

## Licences

These are the licence strings recorded per document in the manifest and stored
alongside each document. They are what the project recorded while collecting the
source; they are not a legal opinion, and where a publisher's terms are general
terms of use rather than an explicit content licence, that is stated in the
licence text itself.

| Licence | Documents | Licence URL |
| --- | --- | --- |
${inventory.licences.map((row) => `| ${row.licence} | ${row.documents} | ${row.licenceUrl ?? "—"} |`).join("\n")}

## Source inventory

| Source id | Title | Publisher | Passages | Retrieved | Review |
| --- | --- | --- | --- | --- | --- |
${inventory.rows.map((row) => line([
  row.sourceId,
  row.title,
  row.publisher,
  row.indexedPassages,
  row.retrievedAt.slice(0, 10),
  row.reviewLabel,
])).join("\n")}

## How a document becomes an answer

1. **Collection.** \`lib/corpus/sources.ts\` is the curated manifest: one entry per
   document with its canonical URL, publisher, topic and licence. The manifest is
   code, so a change to it is a reviewable commit. No source is fetched that is
   not listed there.
2. **Ingestion** (\`lib/rag/ingest.ts\`, \`pnpm ingest\`). Each URL is fetched once
   per run, cleaned to text with \`lib/rag/extract.ts\`, and hashed (SHA-256 of the
   extracted text). A document whose hash is unchanged is skipped, which makes
   re-ingestion idempotent. Each run is recorded in \`ingestion_runs\`.
3. **Chunking** (\`lib/rag/chunk.ts\`). Text is split along its own headings rather
   than fixed windows: paragraphs are packed toward ${1200} characters, never above
   ${1800}, and each chunk repeats a short tail (200 characters) of the previous one
   so a sentence split across a boundary keeps its context.
4. **Indexing** (\`lib/db/sqlite-store.ts\`). Every chunk is stored with its text,
   heading and an embedding produced by the configured provider (Gemini
   \`gemini-embedding-001\`; stored as Float32 BLOBs). A BM25 index is maintained by
   SQLite FTS5 (\`chunks_fts\`).
5. **Retrieval** (\`lib/rag/retrieve.ts\`). Two rankers run over the same chunks:
   exact cosine vector search (a full scan, deterministic for this corpus size)
   and BM25 keyword search over FTS5. Their rankings are combined with reciprocal
   rank fusion; the top ${6} fused chunks become evidence.
6. **Generation and citations** (\`lib/rag/generate.ts\`). The model may only
   answer from the supplied evidence and must cite passages as [S1]..[Sn].
   Citations are validated against the passages actually retrieved; a marker that
   does not resolve is stripped, and the count is reported.
7. **Abstention.** The system declines when the corpus cannot support an answer:
   an out-of-scope question, no usable evidence, or safety screening finds a
   potential emergency (in which case it directs the reader to urgent care and
   stops before retrieval).

## Review status

The governance ledger \`lib/corpus/source-reviews.json\` is in version control and
is currently **empty**: no qualified clinical reviewer has reviewed any document
in this corpus. Every document is therefore reported as "not reviewed", and the
platform makes no clinical validation claim. A review, when recorded, is bound to
the SHA-256 of the exact text it was made against.

## Known limitations and unverified claims

- Licences were recorded by the project operator from each publisher's own
  published terms at collection time. They are attribution labels, not verified
  legal opinions. WHO material is marked CC BY-NC-SA 3.0 IGO (non-commercial);
  MedlinePlus content is "mostly public domain" with third-party exceptions; NHS
  and UKHSA material is marked Open Government Licence v3.0; the NCVBDC page is
  marked as government website content reproduced with acknowledgement.
- The corpus is static by design. Publisher pages change without notice; the
  staleness display on each library page flags copies older than the configured
  age so they can be re-checked.
- Vector search is an exact scan, not an approximate index. This is a deliberate
  trade: deterministic evaluation and simple reasoning in exchange for O(n·d)
  cost, which is measured in \`docs/evaluation.md\`.
- Nothing in this corpus has been clinically validated, and retrieval quality
  figures in \`docs/evaluation.md\` are measured against a single small, hand-built
  question set, so they are an upper estimate.

## Discrepancies found by this run

${
  inventory.discrepancies.length === 0
    ? "None. Every manifest entry is indexed, every indexed document is in the manifest, and URLs, publishers and licences agree between the two."
    : inventory.discrepancies
        .map((item) => `- **${item.kind}** — \`${item.sourceId}\`: ${item.detail}`)
        .join("\n")
}
`;
}

function main(): void {
  if (!fs.existsSync(DB_PATH)) {
    console.error(
      `The retrieval database was not found at ${DB_PATH}. Run \`pnpm ingest\` first.`,
    );
    process.exit(1);
  }

  const inventory = buildInventory();

  // Direct read-only checks on the raw tables that the store's typed API does not
  // expose: embedding coverage, orphaned passages, and empty text.
  const db = new Database(DB_PATH, { readonly: true });
  const totalChunks = db.prepare("SELECT COUNT(*) AS n FROM chunks").get() as { n: number };
  const embedded = db.prepare(
    "SELECT COUNT(*) AS n FROM chunks WHERE embedding IS NOT NULL",
  ).get() as { n: number };
  const orphans = db
    .prepare(
      `SELECT COUNT(*) AS n FROM chunks c
         LEFT JOIN documents d ON d.id = c.document_id
        WHERE d.id IS NULL`,
    )
    .get() as { n: number };
  const empty = db
    .prepare("SELECT COUNT(*) AS n FROM chunks WHERE TRIM(COALESCE(text, '')) = ''")
    .get() as { n: number };
  const ingestionRuns = db
    .prepare("SELECT COUNT(*) AS n FROM ingestion_runs")
    .get() as { n: number };
  const revisions = db
    .prepare("SELECT COUNT(*) AS n FROM document_revisions")
    .get() as { n: number };
  db.close();

  const problems: string[] = [];
  if (totalChunks.n !== inventory.passageCount) {
    problems.push(
      `passage count differs: database has ${totalChunks.n}, inventory has ${inventory.passageCount}`,
    );
  }
  if (embedded.n !== totalChunks.n) {
    problems.push(
      `${totalChunks.n - embedded.n} of ${totalChunks.n} passages have no embedding`,
    );
  }
  if (orphans.n > 0) problems.push(`${orphans.n} orphaned passage(s)`);
  if (empty.n > 0) problems.push(`${empty.n} empty passage(s)`);

  fs.mkdirSync(OUT_DIR, { recursive: true });

  const csv = inventoryToCsv(inventory.rows, { includeLocalLocation: true });
  fs.writeFileSync(path.join(OUT_DIR, "RAG_SOURCE_INVENTORY.csv"), csv, "utf8");

  const json = {
    generatedAt: inventory.generatedAt,
    backend: inventory.backend,
    database: inventory.database,
    documentCount: inventory.documentCount,
    passageCount: inventory.passageCount,
    publishers: inventory.publishers,
    licences: inventory.licences,
    discrepancies: inventory.discrepancies,
    documents: inventory.rows.map((row) => ({
      ...row,
      review: {
        ...reviewFor(row.sourceId, row.contentSha256),
        covering: undefined,
        latest: undefined,
      },
    })),
  };
  fs.writeFileSync(
    path.join(OUT_DIR, "RAG_SOURCE_INVENTORY.json"),
    `${JSON.stringify(json, null, 2)}\n`,
    "utf8",
  );

  fs.writeFileSync(
    path.join(OUT_DIR, "RAG_CORPUS_REPORT.md"),
    buildReport(inventory, {
      embeddedPassages: embedded.n,
      totalEmbeddings: totalChunks.n,
      ingestionRuns: ingestionRuns.n,
      revisionCount: revisions.n,
    }),
    "utf8",
  );

  console.log(`backend:      ${inventory.backend}`);
  console.log(`database:     ${DB_PATH}`);
  console.log(`documents:    ${inventory.documentCount}`);
  console.log(`passages:     ${inventory.passageCount} (embedded ${embedded.n})`);
  console.log(`publishers:   ${inventory.publishers.length}`);
  console.log(`licences:     ${inventory.licences.length}`);
  console.log(`manifest:     ${CORPUS_SOURCES.length} entries`);
  console.log(`discrepancies:${inventory.discrepancies.length}`);
  for (const item of inventory.discrepancies) {
    console.log(`  - ${item.kind}: ${item.sourceId} — ${item.detail}`);
  }
  console.log(`written to:   ${path.relative(process.cwd(), OUT_DIR)}`);

  if (problems.length > 0 || inventory.discrepancies.length > 0) {
    console.error("\nAUDIT FAILED");
    for (const problem of problems) console.error(`  - ${problem}`);
    process.exit(1);
  }
  console.log("\nAUDIT PASSED: every number is backed by a database row.");
}

main();
